// ─── Build flat items array ────────────────────────────────────────────────────

const MONTHS = ["01","02","03","04","05","06","07","08","09","10","11","12"];

const items = [];
for (const [year, closes] of Object.entries(SP500)) {
  closes.forEach((close, i) => {
    items.push({ monthId: `${year}-${MONTHS[i]}`, close });
  });
}

// ─── Batch write (25 items per request — DynamoDB limit) ──────────────────────

async function seed() {
  console.log(`Seeding ${items.length} monthly S&P 500 records into ${TABLE} (${USE_AWS ? "AWS" : "local"})…`);

  for (let i = 0; i < items.length; i += 25) {
    const batch = items.slice(i, i + 25);
    await client.send(new BatchWriteCommand({
      RequestItems: {
        [TABLE]: batch.map(item => ({ PutRequest: { Item: item } })),
      },
    }));
    process.stdout.write(`\r  ${Math.min(i + 25, items.length)}/${items.length}`);
  }

  console.log(`\n✅ Done — ${items.length} records written (${Object.keys(SP500)[0]}-01 → ${Object.keys(SP500).at(-1)}-12).`);
}

seed().catch(e => { console.error("\n❌", e.message); process.exit(1); });
